// Builds the web bundle the Android/iOS apps ship with (www/): the same pages and scripts as the website,
// plus a generated assets/app.config.js with the API address and the public Google client ids for this environment.
//
//   ONWARD_ENV=production node scripts/build-web.mjs
//
// Reads ONWARD_API_BASE, GOOGLE_CLIENT_ID (web client id, also used by the Android SDK) and GOOGLE_IOS_CLIENT_ID from the
// environment or from .env.<ONWARD_ENV> / .env. Only these public values are written into the app — never secrets.
import { cpSync, existsSync, mkdirSync, readFileSync, rmSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const root = join(dirname(fileURLToPath(import.meta.url)), '..');
const out = join(root, 'www');
const envName = process.env.ONWARD_ENV || 'development';

function readEnvFile(file) {
  if (!existsSync(file)) return {};
  const values = {};
  for (const line of readFileSync(file, 'utf8').split(/\r?\n/)) {
    const m = /^\s*([A-Z0-9_]+)\s*=\s*(.*?)\s*$/.exec(line);
    if (m) values[m[1]] = m[2].replace(/^["']|["']$/g, '');
  }
  return values;
}
const fileEnv = { ...readEnvFile(join(root, '.env')), ...readEnvFile(join(root, `.env.${envName}`)) };
const pick = (name, fallback = '') => process.env[name] ?? fileEnv[name] ?? fallback;

const apiBase = pick('ONWARD_API_BASE', pick('APP_BASE_URL')).replace(/\/+$/, '');
if (!/^https:\/\//.test(apiBase) && envName === 'production') {
  console.error('ONWARD_API_BASE must be an https:// address for a production build.');
  process.exit(1);
}

rmSync(out, { recursive: true, force: true });
mkdirSync(out, { recursive: true });
for (const file of ['index.html', 'login.html']) cpSync(join(root, file), join(out, file));
const skip = /(\.md$|[\\/]onward[\\/](manifest|extended-manifest|missing-manifest)\.json$|app\.sw\.js$)/;
cpSync(join(root, 'assets'), join(out, 'assets'), { recursive: true, filter: (src) => !skip.test(src) });

// The apps carry their libraries instead of loading them from CDNs, so they start without a connection.
const nm = (p) => join(root, 'node_modules', p);
const VENDOR = [
  ['https://cdn.jsdelivr.net/npm/bootstrap@5.3.3/dist/css/bootstrap.min.css', 'bootstrap/dist/css/bootstrap.min.css', 'bootstrap.min.css'],
  ['https://cdn.jsdelivr.net/npm/bootstrap@5.3.3/dist/js/bootstrap.bundle.min.js', 'bootstrap/dist/js/bootstrap.bundle.min.js', 'bootstrap.bundle.min.js'],
  ['https://cdnjs.cloudflare.com/ajax/libs/leaflet/1.9.4/leaflet.min.css', 'leaflet/dist/leaflet.css', 'leaflet/leaflet.css'],
  ['https://cdnjs.cloudflare.com/ajax/libs/leaflet/1.9.4/leaflet.min.js', 'leaflet/dist/leaflet.js', 'leaflet/leaflet.js'],
  ['https://cdnjs.cloudflare.com/ajax/libs/font-awesome/6.7.2/css/all.min.css', '@fortawesome/fontawesome-free/css/all.min.css', 'fontawesome/css/all.min.css'],
  ['https://cdnjs.cloudflare.com/ajax/libs/jszip/3.10.1/jszip.min.js', 'jszip/dist/jszip.min.js', 'jszip.min.js'],
  ['https://cdn.jsdelivr.net/npm/protobufjs@7.4.0/dist/protobuf.min.js', 'protobufjs/dist/protobuf.min.js', 'protobuf.min.js'],
];
const vendor = join(out, 'vendor');
cpSync(nm('leaflet/dist/images'), join(vendor, 'leaflet/images'), { recursive: true });
cpSync(nm('@fortawesome/fontawesome-free/webfonts'), join(vendor, 'fontawesome/webfonts'), { recursive: true });
let page = readFileSync(join(out, 'index.html'), 'utf8');
for (const [cdn, source, target] of VENDOR) {
  if (!page.includes(cdn)) throw new Error(`index.html no longer loads ${cdn}; update VENDOR in scripts/build-web.mjs`);
  mkdirSync(dirname(join(vendor, target)), { recursive: true });
  cpSync(nm(source), join(vendor, target));
  page = page.split(cdn).join(`/vendor/${target}`);
}
writeFileSync(join(out, 'index.html'), page);

const config = {
  apiBase,
  google: { webClientId: pick('GOOGLE_CLIENT_ID'), iosClientId: pick('GOOGLE_IOS_CLIENT_ID') },
};
writeFileSync(join(out, 'assets', 'app.config.js'),
  `// Generated by scripts/build-web.mjs (${envName}); public values only.\nwindow.ONWARD_CONFIG = ${JSON.stringify(config, null, 2)};\n`);
console.log(`www/ built for ${envName}: API ${apiBase || '(same origin)'}; Google ${config.google.webClientId ? 'configured' : 'not configured'}`);
